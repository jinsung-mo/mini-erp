-- 2단계: 구매 (발주 → 승인 → 입고)
-- 발주서는 "머리(header) 1 + 품목 줄(line) N" 구조다. 입고도 같은 구조이고, 입고 줄은 어느 발주 줄을 받았는지 가리킨다.

-- 문서 번호는 DB 시퀀스로 매긴다. "오늘 최대 번호 + 1"은 동시에 두 건을 만들면 같은 번호가 나온다.
-- 시퀀스는 롤백돼도 되돌아가지 않아서 번호에 빈칸이 생길 수 있다. 발주·입고 번호는 빈칸이 있어도 괜찮다.
create sequence purchase_order_no_seq;
create sequence goods_receipt_no_seq;

create table purchase_order (
    id           bigint generated by default as identity primary key,
    order_no     varchar(20) not null,
    supplier_id  bigint      not null references partner (id),
    warehouse_id bigint      not null references warehouse (id),
    order_date   date        not null,
    due_date     date,
    status       varchar(20) not null,
    memo         varchar(500),
    -- 낙관적 락: 화면이 본 버전과 지금 버전이 다르면 다른 사람이 먼저 바꾼 것이다
    version      bigint      not null default 0,
    created_at   timestamptz not null,
    created_by   varchar(50) not null,
    updated_at   timestamptz not null,
    updated_by   varchar(50) not null,

    constraint uk_purchase_order_no unique (order_no),
    constraint ck_purchase_order_status check (status in
        ('DRAFT', 'SUBMITTED', 'APPROVED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CLOSED', 'CANCELED')),
    constraint ck_purchase_order_due_date check (due_date is null or due_date >= order_date)
);

comment on table purchase_order is '발주서 머리';
comment on column purchase_order.order_no is '발주 번호 (예: PO-000001)';
comment on column purchase_order.warehouse_id is '입고 창고 (물건을 받을 곳)';
comment on column purchase_order.order_date is '발주일 (업무 일자. 감사 컬럼의 시점과 달리 날짜만 있다)';
comment on column purchase_order.due_date is '납기 요청일';
comment on column purchase_order.status is '상태. 전이 규칙은 PurchaseOrderStatus';

create index ix_purchase_order_supplier on purchase_order (supplier_id);
create index ix_purchase_order_status on purchase_order (status);

create table purchase_order_line (
    id                bigint generated by default as identity primary key,
    purchase_order_id bigint         not null references purchase_order (id),
    line_no           int            not null,
    item_id           bigint         not null references item (id),
    -- KG·L 단위가 있어서 소수 3자리까지. 금액 계산에 float/double을 쓰지 않는다 (0.1 + 0.2 != 0.3)
    quantity          numeric(15, 3) not null,
    unit_price        numeric(15, 2) not null,
    received_quantity numeric(15, 3) not null default 0,

    constraint uk_purchase_order_line unique (purchase_order_id, line_no),
    constraint ck_po_line_quantity check (quantity > 0),
    constraint ck_po_line_unit_price check (unit_price >= 0),
    -- 발주보다 많이 받을 수 없다. 애플리케이션 검사를 동시 요청이 함께 통과해도 여기서 막힌다
    constraint ck_po_line_received check (received_quantity >= 0 and received_quantity <= quantity)
);

comment on column purchase_order_line.received_quantity is '지금까지 입고한 수량 (입고 줄의 합과 같아야 한다)';

create index ix_po_line_item on purchase_order_line (item_id);

-- 상태가 바뀔 때마다 한 줄씩 쌓는다. 누가 언제 승인·반려했는지, 반려·취소 사유가 무엇인지 남는다.
create table purchase_order_event (
    id                bigint generated by default as identity primary key,
    purchase_order_id bigint      not null references purchase_order (id),
    type              varchar(20) not null,
    from_status       varchar(20),
    to_status         varchar(20) not null,
    reason            varchar(500),
    occurred_at       timestamptz not null,
    actor             varchar(50) not null,

    constraint ck_po_event_type check (type in
        ('CREATED', 'SUBMITTED', 'APPROVED', 'REJECTED', 'RECEIVED', 'CLOSED', 'CANCELED'))
);

comment on table purchase_order_event is '발주 상태 변경 이력 (지우거나 고치지 않는다)';

create index ix_po_event_order on purchase_order_event (purchase_order_id);

create table goods_receipt (
    id                bigint generated by default as identity primary key,
    receipt_no        varchar(20) not null,
    purchase_order_id bigint      not null references purchase_order (id),
    warehouse_id      bigint      not null references warehouse (id),
    receipt_date      date        not null,
    memo              varchar(500),
    created_at        timestamptz not null,
    created_by        varchar(50) not null,
    updated_at        timestamptz not null,
    updated_by        varchar(50) not null,

    constraint uk_goods_receipt_no unique (receipt_no)
);

comment on table goods_receipt is '입고 머리. 한 발주를 여러 번 나눠 받을 수 있다 (부분 입고)';
comment on column goods_receipt.warehouse_id is '받은 창고 (발주의 입고 창고를 복사해 둔다. 3단계 재고 원장의 기준)';

create index ix_goods_receipt_order on goods_receipt (purchase_order_id);

create table goods_receipt_line (
    id                     bigint generated by default as identity primary key,
    goods_receipt_id       bigint         not null references goods_receipt (id),
    purchase_order_line_id bigint         not null references purchase_order_line (id),
    item_id                bigint         not null references item (id),
    quantity               numeric(15, 3) not null,

    constraint ck_gr_line_quantity check (quantity > 0)
);

create index ix_gr_line_receipt on goods_receipt_line (goods_receipt_id);
create index ix_gr_line_po_line on goods_receipt_line (purchase_order_line_id);
