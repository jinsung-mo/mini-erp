-- 품목 마스터: 구매·재고·판매의 모든 거래가 이 테이블을 참조한다.
-- 주의: 한 번 적용된 마이그레이션 파일은 수정하지 않는다 (체크섬 불일치로 서버가 뜨지 않는다). 변경은 V2부터 새 파일로.
create table item (
    id         bigint generated by default as identity primary key,
    code       varchar(20)  not null,
    name       varchar(100) not null,
    spec       varchar(100),
    unit       varchar(10)  not null,
    active     boolean      not null default true,
    created_at timestamptz  not null,
    created_by varchar(50)  not null,
    updated_at timestamptz  not null,
    updated_by varchar(50)  not null,

    -- 코드는 업무 키다. 애플리케이션의 중복 검사를 동시에 통과한 요청도 여기서 막힌다 (최종 방어선)
    constraint uk_item_code unique (code),
    constraint ck_item_unit check (unit in ('EA', 'BOX', 'KG', 'L'))
);

comment on table item is '품목 마스터';
comment on column item.code is '품목 코드 (업무 키, 등록 후 변경 불가)';
comment on column item.spec is '규격 (예: M10x30)';
comment on column item.unit is '재고 관리 단위';
comment on column item.active is '사용 여부 (마스터는 삭제하지 않고 사용 중지한다)';
