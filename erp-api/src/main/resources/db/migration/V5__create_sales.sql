-- 4단계: 판매 (수주 → 확정(재고 할당) → 출고)
-- 구조는 구매와 같다: 수주 머리 1 + 줄 N + 상태 이력, 출고 머리 1 + 줄 N (출고 줄은 수주 줄을 가리킨다).

create sequence sales_order_no_seq;
create sequence shipment_no_seq;

create table sales_order (
    id           bigint generated by default as identity primary key,
    order_no     varchar(20) not null,
    customer_id  bigint      not null references partner (id),
    warehouse_id bigint      not null references warehouse (id),
    order_date   date        not null,
    due_date     date,
    status       varchar(20) not null,
    memo         varchar(500),
    version      bigint      not null default 0,
    created_at   timestamptz not null,
    created_by   varchar(50) not null,
    updated_at   timestamptz not null,
    updated_by   varchar(50) not null,

    constraint uk_sales_order_no unique (order_no),
    constraint ck_sales_order_status check (status in
        ('DRAFT', 'CONFIRMED', 'PARTIALLY_SHIPPED', 'SHIPPED', 'CLOSED', 'CANCELED')),
    constraint ck_sales_order_due_date check (due_date is null or due_date >= order_date)
);

comment on table sales_order is '수주서 머리';
comment on column sales_order.order_no is '수주 번호 (예: SO-000001)';
comment on column sales_order.warehouse_id is '출고 창고 (재고를 할당하고 내보낼 곳)';
comment on column sales_order.due_date is '납기 요청일 (고객이 받고 싶은 날)';
comment on column sales_order.status is '상태. 전이 규칙은 SalesOrderStatus';

create index ix_sales_order_customer on sales_order (customer_id);
create index ix_sales_order_status on sales_order (status);

create table sales_order_line (
    id               bigint generated by default as identity primary key,
    sales_order_id   bigint         not null references sales_order (id),
    line_no          int            not null,
    item_id          bigint         not null references item (id),
    quantity         numeric(15, 3) not null,
    unit_price       numeric(15, 2) not null,
    shipped_quantity numeric(15, 3) not null default 0,

    constraint uk_sales_order_line unique (sales_order_id, line_no),
    constraint ck_so_line_quantity check (quantity > 0),
    constraint ck_so_line_unit_price check (unit_price >= 0),
    constraint ck_so_line_shipped check (shipped_quantity >= 0 and shipped_quantity <= quantity)
);

comment on column sales_order_line.shipped_quantity is '지금까지 출고한 수량 (출고 줄의 합과 같아야 한다)';

create index ix_so_line_item on sales_order_line (item_id);

create table sales_order_event (
    id             bigint generated by default as identity primary key,
    sales_order_id bigint      not null references sales_order (id),
    type           varchar(20) not null,
    from_status    varchar(20),
    to_status      varchar(20) not null,
    reason         varchar(500),
    occurred_at    timestamptz not null,
    actor          varchar(50) not null,

    constraint ck_so_event_type check (type in ('CREATED', 'CONFIRMED', 'SHIPPED', 'CLOSED', 'CANCELED'))
);

comment on table sales_order_event is '수주 상태 변경 이력 (지우거나 고치지 않는다)';

create index ix_so_event_order on sales_order_event (sales_order_id);

create table shipment (
    id             bigint generated by default as identity primary key,
    shipment_no    varchar(20) not null,
    sales_order_id bigint      not null references sales_order (id),
    warehouse_id   bigint      not null references warehouse (id),
    ship_date      date        not null,
    memo           varchar(500),
    created_at     timestamptz not null,
    created_by     varchar(50) not null,
    updated_at     timestamptz not null,
    updated_by     varchar(50) not null,

    constraint uk_shipment_no unique (shipment_no)
);

comment on table shipment is '출고 머리. 한 수주를 여러 번 나눠 내보낼 수 있다 (부분 출고)';
comment on column shipment.warehouse_id is '내보낸 창고 (수주의 출고 창고를 복사해 둔다)';

create index ix_shipment_order on shipment (sales_order_id);

create table shipment_line (
    id                  bigint generated by default as identity primary key,
    shipment_id         bigint         not null references shipment (id),
    sales_order_line_id bigint         not null references sales_order_line (id),
    item_id             bigint         not null references item (id),
    quantity            numeric(15, 3) not null,

    constraint ck_shipment_line_quantity check (quantity > 0)
);

create index ix_shipment_line_shipment on shipment_line (shipment_id);
create index ix_shipment_line_so_line on shipment_line (sales_order_line_id);

-- 할당량: 확정한 수주 중 아직 내보내지 않은 수량의 합. 가용 재고 = quantity - allocated_quantity.
-- 현재고와 같은 행에 두어서, 같은 잠금(FOR UPDATE) 안에서 "가용 확인 → 할당"이 한 번에 끝나게 한다.
-- allocated_quantity <= quantity 제약은 일부러 걸지 않는다. 실사에서 분실이 확인되면 현재고가 할당보다 작아질 수 있는데,
-- 제약이 있으면 그 현실을 장부에 기록하는 일(실사 조정) 자체가 막힌다. 그때 가용 재고는 음수로 보이고 화면이 부족을 드러낸다.
alter table stock add column allocated_quantity numeric(15, 3) not null default 0;
alter table stock add constraint ck_stock_allocated check (allocated_quantity >= 0);

comment on column stock.allocated_quantity is '할당량 (확정한 수주의 남은 출고 수량 합). 진행 중 수주 줄에서 다시 계산할 수 있다';

-- 원장에 출고(SHIPMENT)를 더한다. 출고도 입고처럼 어느 출고 줄에서 왔는지 반드시 남긴다
alter table stock_transaction drop constraint ck_stock_txn_type;
alter table stock_transaction add constraint ck_stock_txn_type check (type in ('GOODS_RECEIPT', 'ADJUSTMENT', 'SHIPMENT'));
alter table stock_transaction add constraint ck_stock_txn_shipment_source check (type <> 'SHIPMENT' or source_line_id is not null);
alter table stock_transaction add constraint ck_stock_txn_shipment_sign check (type <> 'SHIPMENT' or quantity < 0);
