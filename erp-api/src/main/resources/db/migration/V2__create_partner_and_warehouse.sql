-- 1단계 ②: 거래처·창고 마스터
-- V1은 이미 적용되었으므로 고치지 않고, 새 테이블은 이 파일로 추가한다.
-- PostgreSQL은 DDL(create table)도 트랜잭션 안에서 실행한다. 이 파일의 문장 하나가 실패하면 파일 전체가 롤백된다.

-- 거래처: 한 회사는 레코드 하나. 공급처(매입)·고객(매출)은 역할 컬럼으로 표시한다.
create table partner (
    id          bigint generated by default as identity primary key,
    code        varchar(20)  not null,
    name        varchar(100) not null,
    business_no varchar(10),
    supplier    boolean      not null,
    customer    boolean      not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null,
    created_by  varchar(50)  not null,
    updated_at  timestamptz  not null,
    updated_by  varchar(50)  not null,

    constraint uk_partner_code unique (code),
    -- 같은 회사를 두 번 등록하지 못하게 한다. NULL끼리는 같은 값으로 보지 않으므로 사업자번호가 없는 거래처는 여러 개 가능
    constraint uk_partner_business_no unique (business_no),
    -- 저장 형식은 숫자 10자리 하나뿐이다. 형식이 섞이면 위 unique 제약이 같은 번호를 다른 값으로 본다 (NULL이면 통과)
    constraint ck_partner_business_no check (business_no ~ '^[0-9]{10}$'),
    -- 역할이 하나도 없는 거래처는 없다
    constraint ck_partner_role check (supplier or customer)
);

comment on table partner is '거래처 마스터';
comment on column partner.code is '거래처 코드 (업무 키, 등록 후 변경 불가. 역할처럼 바뀔 수 있는 의미는 넣지 않는다)';
comment on column partner.business_no is '사업자등록번호 (숫자 10자리. 없으면 NULL: 개인 고객, 해외 거래처)';
comment on column partner.supplier is '공급처 역할 (매입: 발주 대상)';
comment on column partner.customer is '고객 역할 (매출: 수주 대상)';
comment on column partner.active is '사용 여부 (마스터는 삭제하지 않고 사용 중지한다)';

-- 창고: 재고가 놓이는 장소. 재고는 "품목 × 창고" 단위로 쌓인다 (3단계).
create table warehouse (
    id         bigint generated by default as identity primary key,
    code       varchar(20)  not null,
    name       varchar(100) not null,
    location   varchar(200),
    active     boolean      not null default true,
    created_at timestamptz  not null,
    created_by varchar(50)  not null,
    updated_at timestamptz  not null,
    updated_by varchar(50)  not null,

    constraint uk_warehouse_code unique (code)
);

comment on table warehouse is '창고 마스터';
comment on column warehouse.code is '창고 코드 (업무 키, 등록 후 변경 불가)';
comment on column warehouse.location is '위치 (예: 본사 1동)';
comment on column warehouse.active is '사용 여부 (마스터는 삭제하지 않고 사용 중지한다)';
