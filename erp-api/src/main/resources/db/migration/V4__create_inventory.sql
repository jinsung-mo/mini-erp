-- 3단계: 재고 (수불 원장 + 현재고)
-- 재고의 원본은 원장(stock_transaction)이다. 들어오고 나간 사건을 한 줄씩 쌓기만 하고 고치지 않는다.
-- 현재고(stock)는 원장을 품목 × 창고로 합한 값을 미리 저장해 둔 것이다. 화면마다 원장 전체를 더하지 않으려고 둔다.
-- 둘은 항상 같은 트랜잭션에서 함께 바뀐다. 현재고가 원장 합계와 다르면 현재고가 틀린 것이다.

create table stock (
    id           bigint generated by default as identity primary key,
    item_id      bigint         not null references item (id),
    warehouse_id bigint         not null references warehouse (id),
    quantity     numeric(15, 3) not null default 0,
    created_at   timestamptz    not null,
    created_by   varchar(50)    not null,
    updated_at   timestamptz    not null,
    updated_by   varchar(50)    not null,

    -- 품목 × 창고마다 한 줄. 처음 들어오는 품목은 줄을 새로 만드는데, 동시에 두 요청이 만들려 하면 여기서 하나만 남는다
    constraint uk_stock unique (item_id, warehouse_id),
    -- 재고는 음수가 될 수 없다. 애플리케이션 검사가 빠지거나 동시 요청이 함께 통과해도 DB가 마지막에 막는다
    constraint ck_stock_quantity check (quantity >= 0)
);

comment on table stock is '현재고 (품목 × 창고). 원장 합계를 미리 저장해 둔 값';

create index ix_stock_warehouse on stock (warehouse_id);

-- 재고 조정 번호 (ADJ-000001). 입고 번호와 마찬가지로 빈칸이 생겨도 된다
create sequence stock_adjustment_no_seq;

create table stock_transaction (
    id             bigint generated by default as identity primary key,
    item_id        bigint         not null references item (id),
    warehouse_id   bigint         not null references warehouse (id),
    type           varchar(20)    not null,
    -- 들어오면 +, 나가면 -. 방향을 따로 두지 않고 부호로 표현하면 현재고 = sum(quantity)로 끝난다
    quantity       numeric(15, 3) not null,
    -- 이 거래 직후의 현재고. 같은 품목 × 창고의 거래는 현재고 행을 잠근 채 기록하므로 순서대로 쌓인다
    balance_after  numeric(15, 3) not null,
    txn_date       date           not null,
    source_no      varchar(20)    not null,
    source_line_id bigint,
    reason         varchar(500),
    occurred_at    timestamptz    not null,
    actor          varchar(50)    not null,

    constraint ck_stock_txn_type check (type in ('GOODS_RECEIPT', 'ADJUSTMENT')),
    constraint ck_stock_txn_quantity check (quantity <> 0),
    constraint ck_stock_txn_balance check (balance_after >= 0),
    -- 입고는 어느 입고 줄에서 왔는지 반드시 남긴다. 조정은 사유를 반드시 남긴다
    constraint ck_stock_txn_source check (type <> 'GOODS_RECEIPT' or source_line_id is not null),
    constraint ck_stock_txn_reason check (type <> 'ADJUSTMENT' or reason is not null)
);

comment on table stock_transaction is '재고 수불 원장 (지우거나 고치지 않는다. 잘못은 반대 거래로 바로잡는다)';
comment on column stock_transaction.txn_date is '업무 일자 (입고일, 조정일)';
comment on column stock_transaction.source_no is '근거 문서 번호 (GR-000001, ADJ-000001)';
comment on column stock_transaction.source_line_id is '근거 문서 줄 id (입고면 goods_receipt_line.id)';

-- 같은 입고 줄을 원장에 두 번 올리지 않는다 (재시도·버그로 이중 기록되면 재고가 두 배가 된다)
create unique index uk_stock_txn_source_line on stock_transaction (type, source_line_id)
    where source_line_id is not null;
-- 품목 × 창고의 수불부 조회 (최근 순)
create index ix_stock_txn_item_warehouse on stock_transaction (item_id, warehouse_id, id);
create index ix_stock_txn_date on stock_transaction (txn_date);

-- 이관: 2단계에서 이미 처리한 입고를 원장과 현재고에 옮긴다.
-- 3단계 이전 입고는 원장 없이 입고 문서만 있다. 옮기지 않으면 현재고가 0에서 시작해 실제 창고와 어긋난다.
-- 기록 순서는 입고 줄 id 순서, 직후 재고는 같은 품목 × 창고의 누적 합으로 계산한다.
insert into stock_transaction (item_id, warehouse_id, type, quantity, balance_after, txn_date, source_no,
                               source_line_id, reason, occurred_at, actor)
select grl.item_id,
       gr.warehouse_id,
       'GOODS_RECEIPT',
       grl.quantity,
       sum(grl.quantity) over (partition by grl.item_id, gr.warehouse_id order by grl.id),
       gr.receipt_date,
       gr.receipt_no,
       grl.id,
       null,
       gr.created_at,
       gr.created_by
from goods_receipt_line grl
join goods_receipt gr on gr.id = grl.goods_receipt_id
order by grl.id;

insert into stock (item_id, warehouse_id, quantity, created_at, created_by, updated_at, updated_by)
select item_id, warehouse_id, sum(quantity), min(occurred_at), 'migration', max(occurred_at), 'migration'
from stock_transaction
group by item_id, warehouse_id;
